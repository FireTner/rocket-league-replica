REPO_ROOT = os.path.dirname(os.path.dirname(_HERE))
TRACE_DIR = os.path.join(REPO_ROOT, "decomp", "traces")

SUPERSONIC_UU = 2200.0   # G8 threshold, cited: docs/number_gates.md / AGENTS.md
DEFAULT_TOP = 10

#: how the worst frames are ranked when --rank composite (documented weights:
#: one "uu" of focus/distance, ~0.55 deg of rotation, 1 deg of FOV)
RANK_TOLERANCES = {
    "focus_uu": 1.0,
    "distance_uu": 1.0,
    "rotation_mag": 100.0,   # rotator units (~0.55 deg)
    "fov_deg": 1.0,
}

# ── the replay driver (generated, never committed) ──────────────────────────
# Compiled against the real src/camera/Camera.cpp. Whitepace-separated I/O so a
# stray separator can never silently shift a column.
DRIVER_SRC = r"""
// Generated by tools/decomp/camera_trace_diff.py — do not edit, do not commit.
// Replays a cam_trace v1 through the real rl::Camera and prints its GL pair.
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <cstring>

#include "camera/Camera.h"

int main(int argc, char** argv) {
    if (argc < 3) {
        std::fprintf(stderr, "usage: driver in.txt out.txt [key=value ...]\n");
        return 2;
    }
    FILE* in = std::fopen(argv[1], "r");
    if (!in) { std::perror(argv[1]); return 2; }
    FILE* out = std::fopen(argv[2], "w");
    if (!out) { std::perror(argv[2]); return 2; }
    static char obuf[1 << 16];
    std::setvbuf(out, obuf, _IOFBF, sizeof obuf);

    rl::Camera cam;
    rl::CameraParams& p = cam.Params();
    for (int i = 3; i < argc; ++i) {
        const char* kv = argv[i];
        const char* eq = std::strchr(kv, '=');
        if (!eq) continue;
        const char* v = eq + 1;
        auto is = [&](const char* k) {
            const size_t n = std::strlen(k);
            return std::strncmp(kv, k, n) == 0 && (size_t)(eq - kv) == n;
        };
        if (is("fov")) p.fov = (float)std::atof(v);
        else if (is("distance")) p.distance = (float)std::atof(v);
        else if (is("height")) p.height = (float)std::atof(v);
        else if (is("angle")) p.angle = (float)std::atof(v);
        else if (is("stiffness")) p.stiffness = (float)std::atof(v);
        else if (is("transition_speed")) p.transitionSpeed = (float)std::atof(v);
        else if (is("swivel_speed")) p.swivelSpeed = (float)std::atof(v);
        else if (is("snap")) p.snap = std::atoi(v) != 0;
        else if (is("shake")) p.shake = std::atoi(v) != 0;
        else if (is("invert_swivel")) p.invertSwivel = std::atoi(v) != 0;
    }

    int frame = 0;
    for (;;) {
        double dt, cpx, cpy, cpz, cyaw, bpx, bpy, bpz, bcam, speed, super,
               sx, sy, air, fwx, fwy, fwz, vx, vy, vz;
        const int n = std::fscanf(in,
            "%lf %lf %lf %lf %lf %lf %lf %lf %lf %lf %lf %lf %lf %lf "
            "%lf %lf %lf %lf %lf %lf",
            &dt, &cpx, &cpy, &cpz, &cyaw, &bpx, &bpy, &bpz, &bcam, &speed,
            &super, &sx, &sy, &air, &fwx, &fwy, &fwz, &vx, &vy, &vz);
        if (n != 20) break;   // EOF or a malformed frame: stop, count stays
        const float carPos[3] = {(float)cpx, (float)cpy, (float)cpz};
        const float ballPos[3] = {(float)bpx, (float)bpy, (float)bpz};
        const float carFwd[3] = {(float)fwx, (float)fwy, (float)fwz};
        const float carVel[3] = {(float)vx, (float)vy, (float)vz};
        cam.Update((float)dt, carPos, (float)cyaw, ballPos, bcam > 0.5,
                   (float)speed, super > 0.5, (float)sx, (float)sy,
                   carFwd, carVel, air > 0.5);
        float e[3], c[3];
        cam.Eye(e);
        cam.Center(c);
        std::fprintf(out, "%d %.9g %.9g %.9g %.9g %.9g %.9g %.9g %.9g %.9g %.9g\n",
                     frame, e[0], e[1], e[2], c[0], c[1], c[2],
                     cam.EffFov(), cam.SwivelYaw(), cam.SwivelPitch(),
                     cam.Blend());
        ++frame;
    }
    std::fclose(in);
    std::fclose(out);
    std::fprintf(stderr, "driver: %d frames\n", frame);
    return 0;
}
"""

COMPILE_FLAGS = ["-std=c++20", "-O2", "-ffp-contract=off", "-fno-fast-math", "-Isrc"]
CXX = os.environ.get("CXX", "g++")


class DiffError(Exception):
    """Anything that stops a comparison from being made honestly."""


# ── replay backends ─────────────────────────────────────────────────────────
def replay_inputs(tr):
    """Per-frame `Camera::Update()` arguments derived from the trace.

    Convention choices, all documented and none of them guessed silently:
      * `carYaw` (radians, 0 = +X) is the car's UE yaw rotator converted once;
      * `carFwd` is the nose vector of the car's (pitch, yaw) rotator;
      * `carSpeed` is |car velocity| and `supersonic` is the measured G8
        threshold (2200 uu/s) applied to it — a recorder may also store the
        game's own flag, but this keeps the replay independent of the hook;
      * swivel inputs are passed through as recorded (the caller already applied
        the deadzone, per `Camera::Update`'s contract).
    """
    rows = []
    for i in range(tr.record_count):
        car_vel = tr.car_vel(i)
        car_rot = tr.car_rot(i)
        speed = math.sqrt(car_vel[0] ** 2 + car_vel[1] ** 2 + car_vel[2] ** 2)
        cyaw_rad = car_rot[1] / ct.ROT_PER_RAD
        fwd = ct.fwd_from_rotator(car_rot[0], car_rot[1])
        rows.append((
            tr.value(i, "dt"),
            *tr.car_pos(i), cyaw_rad,
            *tr.ball_pos(i),
            1.0 if tr.value(i, "ball_cam") > 0.5 else 0.0,
            speed,
            1.0 if speed >= SUPERSONIC_UU else 0.0,
            tr.value(i, "swivel_in_x"), tr.value(i, "swivel_in_y"),
            1.0 if tr.value(i, "airborne") > 0.5 else 0.0,
            *fwd, *car_vel,
        ))
    return rows


def run_recorded(tr):
    """Self-consistency backend: the trace's own POV through the loader path."""
    frames = []
    for i in range(tr.record_count):
        focus = tr.focus(i)
        eye = ct.eye_from_pov(focus, tr.rotation(i), tr.value(i, "distance"))
        frames.append({"eye": eye, "center": focus,
                       "fov": tr.value(i, "fov"),
                       # the loader's inverse has no independent swivel state,
                       # so CurrentSwivel is not comparable on this path
                       "swivel_yaw": None, "blend": None})
    return frames


def _driver_cache_dir():
    h = hashlib.sha1()
    for rel in ("src/camera/Camera.cpp", "src/camera/Camera.h"):
        with open(os.path.join(REPO_ROOT, rel), "rb") as f:
            h.update(f.read())
    h.update(DRIVER_SRC.encode("utf-8"))
    h.update("".join(COMPILE_FLAGS).encode("utf-8"))
    tag = h.hexdigest()[:16]
    return os.path.join(tempfile.gettempdir(), "rl-cam-driver-" + tag), tag


def build_driver(verbose=True):
    """Compile (or reuse) the replay driver. Returns its path."""
    cache, tag = _driver_cache_dir()
    exe = os.path.join(cache, "cam_replay_driver")
    if os.path.isfile(exe) and os.access(exe, os.X_OK):
        if verbose:
            print("driver     : cached %s (Camera.cpp sha1 %s)" % (exe, tag),
                  file=sys.stderr)
        return exe
    os.makedirs(cache, exist_ok=True)
    src = os.path.join(cache, "cam_replay_driver.cpp")
    with open(src, "w") as f:
        f.write(DRIVER_SRC)
    # Build to a unique name then atomically publish it: two workers (or P3's
    # gate) may race for the same cache entry and no run may see a half-written
    # binary. This writes only inside the private cache dir — never build/ — so
    # it does not need the shared `flock /tmp/rl-build.lock`.
    tmp_exe = "%s.tmp.%d" % (exe, os.getpid())
    cmd = [CXX, *COMPILE_FLAGS, "-o", tmp_exe,
           os.path.join(REPO_ROOT, "src/camera/Camera.cpp"), src, "-lGL"]
    if verbose:
        print("driver     : building (g++ against src/camera/Camera.cpp)",
              file=sys.stderr)
    r = subprocess.run(cmd, cwd=REPO_ROOT, capture_output=True, text=True)
    if r.returncode != 0:
        try:
            os.unlink(tmp_exe)
        except OSError:
            pass
        raise DiffError("driver compile failed:\n  %s\n--- stderr ---\n%s"
                        % (" ".join(cmd), (r.stderr or r.stdout)[-2000:]))
    os.replace(tmp_exe, exe)
    if verbose:
        print("driver     : %s" % exe, file=sys.stderr)
    return exe


def run_ours(tr, verbose=True):
    """Replay through the real `rl::Camera`; returns [(eye, center, fov)]."""
    exe = build_driver(verbose=verbose)
    inputs = replay_inputs(tr)
    tmp = tempfile.mkdtemp(prefix="rl-cam-replay-")
    try:
        inpath = os.path.join(tmp, "in.txt")
        outpath = os.path.join(tmp, "out.txt")
        with open(inpath, "w") as f:
            for row in inputs:
                f.write(" ".join("%.9g" % v for v in row) + "\n")
        setts = tr.header.get("settings", {})
        params = [
            "fov=%.9g" % setts.get("fov", ct.DEFAULT_SETTINGS["fov"]),
            "distance=%.9g" % setts.get("distance", ct.DEFAULT_SETTINGS["distance"]),
            "height=%.9g" % setts.get("height", ct.DEFAULT_SETTINGS["height"]),
            "angle=%.9g" % setts.get("pitch", ct.DEFAULT_SETTINGS["pitch"]),
            "stiffness=%.9g" % setts.get("stiffness", ct.DEFAULT_SETTINGS["stiffness"]),
            "transition_speed=%.9g" % setts.get("transition_speed",
                                                ct.DEFAULT_SETTINGS["transition_speed"]),
            "swivel_speed=%.9g" % setts.get("swivel_speed",
                                            ct.DEFAULT_SETTINGS["swivel_speed"]),
            "snap=%d" % (1 if setts.get("snap", True) else 0),
            "shake=%d" % (1 if setts.get("camera_shake", True) else 0),
            "invert_swivel=%d" % (1 if setts.get("invert_swivel_pitch", False) else 0),
        ]
        r = subprocess.run([exe, inpath, outpath, *params],
                           capture_output=True, text=True)
        if r.returncode != 0:
            raise DiffError("replay driver failed (exit %d):\n%s"
                            % (r.returncode, (r.stderr or "")[-2000:]))
        frames = []
        with open(outpath) as f:
            for line in f:
                parts = line.split()
                if len(parts) < 10:
                    continue
                v = [float(x) for x in parts[1:11]]
                frames.append({
                    "eye": (v[0], v[1], v[2]),
                    "center": (v[3], v[4], v[5]),
                    "fov": v[6],
                    "swivel_yaw": v[7],
                    "blend": v[9],
                })
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    if len(frames) != tr.record_count:
        raise DiffError("replay produced %d frames for %d records — the driver "
                        "stopped early (malformed input row?)"
                        % (len(frames), tr.record_count))
    return frames


# ── comparison ──────────────────────────────────────────────────────────────
def convention_status(tr):
    """Which comparisons are trustworthy, and why the rest are UNVERIFIED."""
    h = tr.header
    reasons = []
    pov_ok = h.get("pov_convention") in ct.SUPPORTED_POV_CONVENTIONS
    if not pov_ok:
        reasons.append("pov_convention=%r is not %r" %
                       (h.get("pov_convention"), ct.SUPPORTED_POV_CONVENTIONS))
    roll_max = 0.0
    roll_nonzero = 0
    for i in range(tr.record_count):
        v = abs(tr.value(i, "rot_roll"))
        if v > 1e-6:
            roll_nonzero += 1
            roll_max = max(roll_max, v)
    swivel_ok = h.get("swivel_convention") == "radians"
    return {
        "pov": pov_ok,
        "reasons": reasons,
        "roll_nonzero_frames": roll_nonzero,
        "roll_abs_max": roll_max,
        "roll": roll_nonzero == 0,
        "swivel": swivel_ok,
        "swivel_reason": ("header swivel_convention=%r (RL CurrentSwivel's unit "
                          "is not established by the decompile)"
                          % h.get("swivel_convention")),
        "time": False,
        "time_reason": "Camera exposes no POV-clock accessor (OutPOV.Time only)",
    }


def compare(tr, frames):
    """Per-frame per-field errors. Same definition the self-check uses."""
    rows = []
    skipped = 0
    for i, fr in enumerate(frames):
        eye, center, fov = fr["eye"], fr["center"], fr["fov"]
        rec = {
            "focus": tr.focus(i),
            "rotation": tr.rotation(i),
            "distance": tr.value(i, "distance"),
            "fov": tr.value(i, "fov"),
            "time": tr.value(i, "out_time"),
        }
        derived = ct.pov_from_eye_center(eye, center, fov, rec["time"])
        if derived is None:
            skipped += 1
            continue
        e = ct.pov_field_errors(rec, derived, quantize=True)
        e["frame"] = i
        e["t"] = rec["time"]
        # the two distances being compared, so the semantics probe is auditable
        e["ours_distance"] = derived["distance"]
        e["rec_distance"] = rec["distance"]
        # CurrentSwivel: only comparable when the header declares radians AND
        # the backend has its own swivel state (the loader inverse does not).
        sw = fr.get("swivel_yaw")
        e["swivel_rad"] = (None if sw is None
                           else _wrap_pi(sw - tr.value(i, "current_swivel_yaw")))
        rows.append(e)
    return rows, skipped


def _wrap_pi(a):
    """Wrap an angle to (-pi, pi] (same helper cam_trace uses)."""
    a = math.fmod(a + math.pi, 2.0 * math.pi)
    if a <= 0.0:
        a += 2.0 * math.pi
    return a - math.pi


def distance_semantics(rows):
    """Is |Eye - Center| the same quantity the trace records as Distance?

    This is the one place the POV convention can genuinely be ambiguous, and the
    tool refuses to guess. Two readings of RL's `OutPOV.Distance` are defensible:

      * **camera-focus** — Distance is how far the eye sits behind the Focus, so
        |Eye - Center| IS the recorded value (this tool's convention);
      * **rig-length** — Focus is the look target and Distance is the rig slider,
        so |Eye - Center| is the distance to that target (hundreds of uu more).

    The probe is empirical, not declared: compare the medians. A ratio inside
    [0.5, 2.0] means the two agree well enough that the comparison is meaningful.
    """
    ours = [r["ours_distance"] for r in rows]
    rec = [r["rec_distance"] for r in rows]
    med_ours = ct._median(ours)
    med_rec = ct._median(rec)
    ratio = (med_ours / med_rec) if med_rec > 1e-6 else float("inf")
    ok = 0.5 <= ratio <= 2.0
    return {"ok": ok, "ratio": ratio, "med_ours": med_ours, "med_rec": med_rec}


def trace_pov_probe(tr):
    """Median |eye_from_pov - car| and |focus - car| for the trace's own POV.

    Reported so a human can see which reading the recording used without the tool
    having to assert one: a chase camera's eye is near the car (hundreds of uu),
    an "eye parked behind the focus target" POV is not.
    """
    eyes, focuses = [], []
    for i in range(tr.record_count):
        focus = tr.focus(i)
        eye = ct.eye_from_pov(focus, tr.rotation(i), tr.value(i, "distance"))
        car = tr.car_pos(i)
        eyes.append(math.dist(eye, car))
        focuses.append(math.dist(focus, car))
    return {"eye_from_car_median": ct._median(eyes),
            "focus_from_car_median": ct._median(focuses)}


class Stat:
    __slots__ = ("vals",)

    def __init__(self):
        self.vals = []

    def add(self, v):
        self.vals.append(abs(v))

    @property
    def n(self):
        return len(self.vals)

    @property
    def max(self):
        return max(self.vals) if self.vals else float("nan")

    @property
    def median(self):
        if not self.vals:
            return float("nan")
        s = sorted(self.vals)
        n = len(s)
        return s[n // 2] if n % 2 else 0.5 * (s[n // 2 - 1] + s[n // 2])


FIELD_REPORT = (
    ("focus_uu", "Focus (3D)", "uu"),
    ("focus_axis_uu", "Focus (per-axis max)", "uu"),
    ("distance_uu", "Distance", "uu"),
    ("rot_pitch", "Rotation pitch", "rotator units"),
    ("rot_yaw", "Rotation yaw", "rotator units"),
    ("rotation_mag", "Rotation magnitude", "rotator units"),
    ("fov_deg", "FOV", "degrees"),
)


def summarise(rows):
    stats = {k: Stat() for k, _, _ in FIELD_REPORT}
    stats["swivel_rad"] = Stat()
    for r in rows:
        for k, _, _ in FIELD_REPORT:
            stats[k].add(r[k])
        if r.get("swivel_rad") is not None:
            stats["swivel_rad"].add(r["swivel_rad"])
    return stats


def rank_key(rows, rank):
    if rank == "focus":
        return lambda r: r["focus_uu"]
    if rank == "distance":
        return lambda r: r["distance_uu"]
    if rank == "rotation":
        return lambda r: r["rotation_mag"]
    if rank == "fov":
        return lambda r: r["fov_deg"]
    def composite(r):
        return max(r[k] / tol for k, tol in RANK_TOLERANCES.items())
    return composite


def format_table(stats, conv, flags):
    out = []
    out.append("%-22s %-15s %14s %14s" % ("FIELD", "UNIT", "MAX", "MEDIAN"))
    out.append("-" * 68)
    for key, label, unit in FIELD_REPORT:
        st = stats[key]
        mark = "  *" if key == "distance_uu" and not flags["distance"] else ""
        out.append("%-22s %-15s %14.6f %14.6f%s"
                   % (label, unit, st.max, st.median, mark))
    out.append("%-22s %-15s %14s %14s"
               % ("Rotation roll", "rotator units", "UNVERIFIED", "UNVERIFIED"))
    out.append("%-22s %-15s %14s %14s"
               % ("POV time", "s", "UNVERIFIED", "UNVERIFIED"))
    sw = stats["swivel_rad"]
    if conv["swivel"] and sw.n:
        out.append("%-22s %-15s %14.6f %14.6f"
                   % ("CurrentSwivel yaw", "radians", sw.max, sw.median))
    elif conv["swivel"]:
        out.append("%-22s %-15s %14s %14s"
                   % ("CurrentSwivel yaw", "radians",
                      "n/a (backend)", "n/a (backend)"))
    else:
        out.append("%-22s %-15s %14s %14s"
                   % ("CurrentSwivel yaw", "header units", "UNVERIFIED",
                      "UNVERIFIED"))
    return out


def format_worst(tr, rows, rank, top):
    key = rank_key(rows, rank)
    worst = sorted(rows, key=key, reverse=True)[:top]
    out = []
    out.append("")
    out.append("TEN WORST FRAMES (rank=%s)" % rank)
    for r in worst:
        i = r["frame"]
        car = tr.car_pos(i)
        cv = tr.car_vel(i)
        ball = tr.ball_pos(i)
        speed = math.sqrt(cv[0] ** 2 + cv[1] ** 2 + cv[2] ** 2)
        out.append(
            "  #%04d t=%7.4fs  focus=%9.3fuu dist=%9.3fuu rot=%9.2fru "
            "fov=%8.3fdeg"
            % (i, r["t"], r["focus_uu"], r["distance_uu"], r["rotation_mag"],
               r["fov_deg"]))
        out.append(
            "         car=(%8.1f,%8.1f,%8.1f) speed=%7.1f%s air=%d ballcam=%d "
            "swivel_in=(%+.2f,%+.2f) dt=%.4f"
            % (car[0], car[1], car[2], speed, " SUPER" if speed >= SUPERSONIC_UU else "",
               1 if tr.value(i, "airborne") > 0.5 else 0,
               1 if tr.value(i, "ball_cam") > 0.5 else 0,
               tr.value(i, "swivel_in_x"), tr.value(i, "swivel_in_y"),
               tr.value(i, "dt")))
        out.append(
            "         ball=(%8.1f,%8.1f,%8.1f) throttle=%+.2f steer=%+.2f "
            "boost=%d jump=%d"
            % (ball[0], ball[1], ball[2], tr.value(i, "throttle"),
               tr.value(i, "steer"), 1 if tr.value(i, "boost") > 0.5 else 0,
               1 if tr.value(i, "jump") > 0.5 else 0))
    return out


