# ── trace discovery ────────────────────────────────────────────────────────
def scan_traces(root=None):
    root = root or TRACE_DIR
    found = []
    for dirpath, _dirnames, filenames in os.walk(root):
        if os.path.basename(dirpath).startswith("."):
            continue
        for name in sorted(filenames):
            if not name.endswith(".rlt"):
                continue
            path = os.path.join(dirpath, name)
            try:
                tr = ct.load(path, strict=False)
            except ct.TraceError as e:
                found.append({"path": path, "error": str(e)})
                continue
            found.append({
                "path": path,
                "source": tr.source,
                "scenario": tr.header.get("scenario"),
                "records": tr.record_count,
                "seed": tr.header.get("seed"),
                "bytes": tr.file_size,
            })
    return found


def cmd_report(a):
    found = scan_traces(a.tracedir)
    print("TRACE SCAN %s" % (a.tracedir or TRACE_DIR))
    if not found:
        print("  (no .rlt files)")
    live = []
    for f in found:
        if "error" in f:
            print("  BROKEN  %-52s %s" % (os.path.basename(f["path"]), f["error"]))
            continue
        tag = "LIVE" if f["source"] == "live" else "fixture"
        print("  %-7s %-52s %5d rec %7d B seed=%s"
              % (tag, os.path.basename(f["path"]), f["records"], f["bytes"],
                 f["seed"]))
        if f["source"] == "live":
            live.append(f)
    print("")
    if not live:
        print("CAMERA ERROR TABLE: NOT AVAILABLE (no recorded trace)")
        print("  reason: no trace under %s declares source=\"live\""
              % (a.tracedir or TRACE_DIR))
        print("  what §6 P2 asks for - our camera's current error table - needs a")
        print("  real recording (wave W3, offline freeplay, an instance the worker")
        print("  launches itself). The synthetic fixtures prove the FORMAT and the")
        print("  REPLAY plumbing; their error tables are not evidence about our")
        print("  camera's accuracy and must not be reported as such.")
        print("  next : python3 tools/decomp/camera_trace_diff.py --self-check")
        return 3
    print("CAMERA ERROR TABLE: %d live trace(s) available" % len(live))
    for f in live:
        print("  -> %s" % f["path"])
    return 0


def cmd_self_check(a):
    """Self-consistency gate: replay the recorded POV through the loader path."""
    import tempfile as _tf
    if a.trace:
        tr = ct.load(a.trace)
        keep = False
    else:
        tmp = _tf.mkdtemp(prefix="rl-selfcheck-")
        path = os.path.join(tmp, "selfcheck.rlt")
        header, rows = ct.generate_synthetic(scenario="swivel-sweep-release",
                                             frames=a.frames, seed=a.seed)
        ct.write_trace(path, header, rows)
        tr = ct.load(path)
        keep = True
    frames = run_recorded(tr)
    rows, skipped = compare(tr, frames)
    conv = convention_status(tr)
    stats = print_report(tr, rows, skipped, "recorded", a.rank, a.top, conv)
    print("")
    worst = max(s.max for s in stats.values())
    ok = worst == 0.0 and skipped == 0
    print("SELFCHECK %s  every field replayed through the loader path, "
          "max_err=%.9f (exactly 0.0 required)" % ("PASS" if ok else "FAIL", worst))
    if keep:
        shutil.rmtree(tmp, ignore_errors=True)
    return 0 if ok else 2


def cmd_diff(a):
    tr = ct.load(a.trace)
    conv = convention_status(tr)
    camera = a.camera
    if camera == "auto":
        camera = "ours"
    frames = run_recorded(tr) if camera == "recorded" else run_ours(tr)
    rows, skipped = compare(tr, frames)
    if a.json == "-":
        # machine-readable only: the human table goes to stderr so stdout stays
        # a single JSON document P3's gate can load
        real_stdout, sys.stdout = sys.stdout, sys.stderr
        try:
            stats = print_report(tr, rows, skipped, camera, a.rank, a.top, conv)
        finally:
            sys.stdout = real_stdout
    else:
        stats = print_report(tr, rows, skipped, camera, a.rank, a.top, conv)
    if a.json:
        payload = {
            "trace": tr.path,
            "source": tr.source,
            "scenario": tr.header.get("scenario"),
            "camera": camera,
            "frames": len(rows),
            "convention_verified": conv["pov"],
            "fields": {k: {"max": stats[k].max, "median": stats[k].median,
                           "unit": u, "n": stats[k].n}
                       for k, _, u in FIELD_REPORT},
            "unverified": {
                "roll": not conv["roll"],
                "pov_time": True,
                "swivel": not conv["swivel"],
            },
        }
        text = json.dumps(payload, indent=2, sort_keys=True)
        if a.json == "-":
            print(text)
        else:
            d = os.path.dirname(os.path.abspath(a.json))
            if d:
                os.makedirs(d, exist_ok=True)
            with open(a.json, "w") as f:
                f.write(text + "\n")
            print("json       : %s" % a.json)
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Replay a camera trace through our camera and print the "
                    "per-field error table (§6 P2.4).")
    ap.add_argument("--trace", help="trace file (.rlt)")
    ap.add_argument("--camera", default="auto", choices=("auto", "ours", "recorded"),
                    help="replay backend (default: ours = the real Camera.cpp)")
    ap.add_argument("--rank", default="composite",
                    choices=("composite", "focus", "distance", "rotation", "fov"),
                    help="how the worst frames are ranked")
    ap.add_argument("--top", type=int, default=DEFAULT_TOP)
    ap.add_argument("--json", nargs="?", const="-", default=None,
                    metavar="PATH",
                    help="dump a machine-readable summary; '-' (default) = "
                         "JSON on stdout with the table on stderr")
    ap.add_argument("--self-check", action="store_true",
                    help="self-consistency: recorded POV through the loader path")
    ap.add_argument("--report", action="store_true",
                    help="scan decomp/traces and say whether a live trace exists")
    ap.add_argument("--tracedir", default=None, help="override the scan directory")
    ap.add_argument("--frames", type=int, default=240,
                    help="frames for the generated self-check fixture")
    ap.add_argument("--seed", type=int, default=7)
    a = ap.parse_args(argv)
    try:
        if a.self_check:
            return cmd_self_check(a)
        if a.report:
            return cmd_report(a)
        if not a.trace:
            ap.print_help()
            return 1
        return cmd_diff(a)
    except ct.TraceError as e:
        print("cam_trace_diff: TRACE ERROR: %s" % e, file=sys.stderr)
        return 2
    except DiffError as e:
        print("cam_trace_diff: %s" % e, file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
