    flags = {"distance": dsem["ok"]}
    for line in banner(tr, camera):
        print(line)
    print("comparison : float32 field precision (the trace's own), %d frames%s"
          % (len(rows), ", %d degenerate skipped" % skipped if skipped else ""))
    print("")
    print("\n".join(format_table(stats, conv, flags)))
    print("")
    print("CONVENTION: %s" % ("VERIFIED — the numbers above are comparable"
                              if conv["pov"] else
                              "UNVERIFIED — %s; treat every number as raw "
                              "diagnostic only" % "; ".join(conv["reasons"])))
    print("  roll    : %s%s"
          % ("UNVERIFIED (our rig never rolls; excluded from scoring)"
             if not conv["roll"] else
             "0 everywhere in this trace (nothing to compare)",
             "" if not conv["roll_nonzero_frames"] else
             "  [%d frames with |roll|>0, max %.1f ru]"
             % (conv["roll_nonzero_frames"], conv["roll_abs_max"])))
    print("  time    : UNVERIFIED — %s" % conv["time_reason"])
