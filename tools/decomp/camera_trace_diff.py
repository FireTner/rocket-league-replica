        print("  distance: * UNVERIFIED — median |Eye-Center| %.1f uu vs recorded "
              "Distance %.1f uu (ratio %.2f)"
              % (dsem["med_ours"], dsem["med_rec"], dsem["ratio"]))
        print("            the trace's POV.Distance is the rig length while our")
        print("            Center() is the look target: comparing them scores a")
        print("            semantic difference, not a camera error. Focus/Rotation/")
        print("            FOV stay comparable; Distance needs a P3 accessor for")
        print("            PovSnapshot.pov.distance (Camera.cpp writes it, the")
        print("            public API does not expose it).")
